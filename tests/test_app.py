"""The combined window, the Document Schema tab and the connect dialog (against the SQLite sample)."""

import time

import pytest
from PySide6.QtCore import QCoreApplication, QSettings, Qt

from data_editor.connect_dialog import ConnectDialog, without_password
from data_editor.main_window import DOCUMENT_TAB, MainWindow
from data_editor.session import open_url


def wait_until(condition, timeout=20):
    end = time.monotonic() + timeout
    while not condition():
        assert time.monotonic() < end, "timed out"
        QCoreApplication.processEvents()
        time.sleep(0.01)


@pytest.fixture
def window(sample_db):
    w = MainWindow(open_url(f"sqlite:///{sample_db}"))
    w.show()
    wait_until(lambda: not w.busy)
    yield w
    w.close()


def test_non_sql_server_connection_opens_document_tab(window):
    assert window.tabs.currentIndex() == DOCUMENT_TAB
    assert window.editor.stack.currentIndex() == 1  # "editing needs SQL Server" message
    assert not window.db_combo.isVisible()
    assert "sqlite: sample" in window.conn_label.text()


def test_lists_and_ticks_tables(window):
    page = window.document
    names = [i.text() for i in page.table_list.items()]
    assert "orders" in names and len(names) == 8
    assert not page.generate_button.isEnabled()

    orders = page.table_list.findItems("orders", Qt.MatchExactly)[0]
    page.table_list.toggle(orders)
    assert page.table_list.checked() == ["orders"]
    assert page.generate_button.isEnabled()

    page.table_search.setText("order")
    page.select_all()
    assert page.table_list.checked() == ["order_items", "orders"]  # only the visible ones
    page.select_none()
    assert page.table_list.checked() == []


def test_generates_document(window, tmp_path):
    page = window.document
    page.select_all()
    page.open_after.setChecked(False)
    page.fmt_html.setChecked(True)
    page.generate_to(str(tmp_path / "shop.html"), page.table_list.checked())
    assert window.busy and not window.act_connect.isEnabled()
    wait_until(lambda: not window.busy)
    html = (tmp_path / "shop.html").read_text(encoding="utf-8")
    assert "Entity relationship diagram" in html
    assert "Generated by Data Editor" in html


def test_connect_dialog_shows_fields_for_the_type():
    d = ConnectDialog()
    form = d.form
    d.kind.setCurrentText("SQL Server")
    assert form.isRowVisible(d.auth) and form.isRowVisible(d.driver) and not form.isRowVisible(d.port)
    d.auth.setCurrentText("Windows Authentication")
    assert not d.username.isEnabled() and not d.password.isEnabled()
    d.host.clear()
    d.connect_to_database()
    assert "server name" in d.status.text()

    d.kind.setCurrentText("PostgreSQL")
    assert form.isRowVisible(d.port) and not form.isRowVisible(d.auth) and d.port.text() == "5432"
    assert d.username.isEnabled()  # Windows sign-in only applies to SQL Server
    d.host.setText("db.local")
    d.database.clear()
    d.connect_to_database()
    assert "database name" in d.status.text()

    d.kind.setCurrentText("SQLite")
    assert form.isRowVisible(d.file.parentWidget()) and not form.isRowVisible(d.host)


def test_remembers_data_editor_1_settings():
    s = QSettings()
    s.setValue("login/server", r"sql01\PROD")
    s.setValue("login/username", "taylor")
    s.setValue("login/auth", "Windows Authentication")
    d = ConnectDialog()
    assert d.kind.currentText() == "SQL Server"
    assert d.host.text() == r"sql01\PROD" and d.username.text() == "taylor"
    assert d.auth.currentText() == "Windows Authentication"


def test_passwords_are_not_remembered():
    assert without_password("postgresql://me:secret@db/app") == "postgresql://me@db/app"
    assert without_password("sqlite:///x.db") == "sqlite:///x.db"


def test_mssql_urls_use_odbc():
    from data_editor.db import available_drivers
    from schemadoc.connection import normalize_url

    url = normalize_url("mssql://me:pw@sql01/Sales")
    assert url.drivername == "mssql+pyodbc"
    if available_drivers():
        assert url.query["driver"] == available_drivers()[0]
